let grade = "A";
// Tulis kode switch statement di sini

switch (grade){
    case "A":
        console.log("Grade A: Sangat baik");
        break;
    case "B":
        console.log("Grade B: Baik");
        break;
    case "C":
        console.log("Grade C: Cukup");
        break;
    case "D":
        console.log("Grade D: kurang");
        break;
    case "E": 
        console.log("Grade E: Sangat Kurang");
        break;
        default:
        console.log("Grade tidak valid");
}


