let size = "L";

switch (size) {
  case "S":
    console.log("Size : Small (36-38)");
    break;
  case "M":
    console.log("Size : Medium (38-42)"); 
    break;
  case "L":
    console.log("Size : Large (44-46)");
    break;
  case "XL":
    console.log("Size : Extra Large (48-50)");
    break;
  default:
    console.log("Size tidak tersedia");
}