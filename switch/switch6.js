let warna = "kuning";
// Tulis kode switch statement di sini



switch (warna) {
  case "merah":
    console.log("Lampu merah: Berhenti");
    break;
  case "kuning":
    console.log("Lampu kuning: Hati-hati, bersiap berhenti");
    break;
  case "hijau":
    console.log("Lampu hijau: Silakan jalan");
    break;
  default:
    console.log("Warna tidak valid / Lampu rusak");
    break;
}